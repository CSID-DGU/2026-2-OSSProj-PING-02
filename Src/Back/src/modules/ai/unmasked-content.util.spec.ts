import { findUnmaskedKinds } from './unmasked-content.util';

describe('findUnmaskedKinds (서버 쪽 마지막 안전장치)', () => {
  it.each([
    ['휴대폰', '내 번호 010-1234-5678 로 연락해', 'phone'],
    ['붙여 쓴 휴대폰', '01012345678로 전화해', 'phone'],
    ['공백으로 나눈 휴대폰', '010 1234 5678로 연락줘', 'phone'],
    ['가운뎃점 휴대폰', '010·1234·5678 이걸로 연락줘', 'phone'],
    ['국제 표기', '+82 10 1234 5678', 'phone'],
    ['국제 표기 하이픈', '+82-10-1234-5678', 'phone'],
    ['서울 지역번호', '사무실 02-123-4567', 'phone'],
    ['괄호 지역번호', '(02) 123-4567 로 전화', 'phone'],
    ['지방 지역번호', '051-234-5678 이에요', 'phone'],
    ['인터넷 전화', '070-1234-5678', 'phone'],
    ['안심번호', '0505-123-4567', 'phone'],
    ['이메일', 'a.b@example.com 으로 보내줘', 'email'],
    ['http 링크', '여기 봐 https://example.com/x', 'url'],
    ['www 링크', 'www.example.com 들어가봐', 'url'],
    ['도메인만', 'naver.com 에서 찾아봐', 'url'],
    ['은행 이름 + 하이픈 계좌', '신한 110-123-456789 로 보내', 'account'],
    ['은행 이름 붙여 쓴 계좌', '신한110-123-456789로 보내', 'account'],
    ['숫자 사이 공백 계좌', '신한 110 123 456789로 보내줘', 'account'],
    ['은행 이름이 뒤에', '110-123-456789 신한으로 보내줘', 'account'],
    ['입금 + 연속 숫자', '3333012345678 로 입금해줘', 'account'],
    ['은행 이름 뒤 연속 숫자', '3333012345678 카카오뱅크', 'account'],
    ['주민등록번호', '990101-1234567', 'national_id'],
    ['외국인등록번호', '990101-5234567', 'national_id'],
  ])('%s 를 찾는다', (_label, text, kind) => {
    expect(findUnmaskedKinds(text)).toContain(kind);
  });

  it('전화번호는 계좌번호로 한 번 더 잡지 않는다 (근처에 은행 이름이 있어도)', () => {
    expect(findUnmaskedKinds('내 번호 010-9876-5432')).toEqual(['phone']);
    expect(findUnmaskedKinds('신한 다니는 친구 번호 010-9876-5432')).toEqual(['phone']);
  });

  it('한 문장에 여러 종류가 있으면 모두 알려 준다', () => {
    expect(findUnmaskedKinds('010-1234-5678 이나 a@b.com, 신한 123-45-678901').sort()).toEqual(
      ['account', 'email', 'phone', 'url'].sort(),
    );
  });

  it.each([
    // 앱 마스킹이 지나간 결과의 자리표시자
    '[이름1]아 회비 3만원 신한 [계좌번호1] (예금주 [이름2])로 보내줘~',
    '번호 바뀌었어 [전화번호1] 저장해줘. 메일은 [이메일1]',
    '[친구A] 가 내일 [장소A] 에서 보자고 했어',
    // 개인정보가 아닌 숫자 (막으면 안 되는 정상 메시지)
    '주문번호 2026-0925-1234 확인해줘',
    '운송장 123456789012 조회해봐',
    '예약번호 20261118-0042 입니다',
    '2026-11-18 에 만나자',
    '오후 3:30 에 보자',
    '3만원만 빌려줄 수 있어?',
    '10000원 보냈어',
    '1층 102호 앞에서 기다릴게',
    '점수 98점 받았어',
    '2호선 강남역 11번 출구',
    // 계좌 모양이지만 단서가 없음 (앱 마스킹도 가리지 않는 경우)
    '110-123-456789 이거 뭐야',
    // 일상어와 겹치는 은행 이름은 단서로 보지 않음
    '우리 집 2026-0925-1234 로 주문했어',
    // 날짜가 아닌 13자리 (주민번호 아님)
    '991399-1234567 은 뭐지',
  ])('막지 않는다: %s', (text) => {
    expect(findUnmaskedKinds(text)).toEqual([]);
  });
});
